import * as FileSystem from 'expo-file-system';

// Expo-compatible R2 upload using signed URL approach.
// For now this uses a direct public-bucket style upload when the bucket allows it.
// Long-term (recommended): generate a short-lived signed URL from a Cloud Function or backend.

const ENDPOINT = process.env.EXPO_PUBLIC_R2_ENDPOINT;
const BUCKET = process.env.EXPO_PUBLIC_R2_BUCKET;
const ACCESS_KEY = process.env.EXPO_PUBLIC_R2_ACCESS_KEY_ID;
const SECRET_KEY = process.env.EXPO_PUBLIC_R2_SECRET_ACCESS_KEY;

export async function uploadFile(localUri: string, key: string, contentType: string): Promise<string> {
  if (!ENDPOINT || !BUCKET) {
    throw new Error('R2 environment variables missing');
  }

  // Read the file as base64 then convert to a blob for upload
  const base64 = await FileSystem.readAsStringAsync(localUri, {
    encoding: FileSystem.EncodingType.Base64,
  });

  const binary = Uint8Array.from(atob(base64), c => c.charCodeAt(0));
  const blob = new Blob([binary], { type: contentType });

  const url = `${ENDPOINT}/${BUCKET}/${key}`;

  // Simple PUT. Works if the bucket is configured for public writes or you later
  // replace this with a signed URL generated by a backend.
  const response = await fetch(url, {
    method: 'PUT',
    headers: {
      'Content-Type': contentType,
    },
    body: blob,
  });

  if (!response.ok) {
    const text = await response.text();
    throw new Error(`R2 upload failed: ${response.status} ${text}`);
  }

  return url;
}
